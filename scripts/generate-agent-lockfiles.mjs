#!/usr/bin/env node
// Generates the app-shipped npm lockfiles of the npx-distributed agents (D72,
// docs/design/28-external-agents-acp.md §2.1 「npm 安装锁精确版本（含锁文件）」).
//
//   pnpm --filter @kepcup/shared run build
//   node scripts/generate-agent-lockfiles.mjs
//
// For every curated catalog entry with `distribution.npx`, resolves the pinned
// package with `npm install --package-lock-only --ignore-scripts --omit=dev` in
// a scratch directory and writes package.json + package-lock.json into
// packages/core/src/agent/external/npx-lockfiles.generated.ts. The installer
// then runs `npm ci --ignore-scripts` against exactly this tree, so transitive
// ranges (e.g. codex-acp → @openai/codex ^x) cannot drift. Re-run whenever a
// catalog version is bumped; the core unit test fails while a lockfile is
// missing.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const sharedDist = path.join(root, 'packages', 'shared', 'dist', 'index.js');
const output = path.join(
  root,
  'packages',
  'core',
  'src',
  'agent',
  'external',
  'npx-lockfiles.generated.ts',
);

const { AGENT_CATALOG } = await import(pathToFileURL(sharedDist).href);

function parseSpec(spec, fallbackVersion) {
  const at = spec.lastIndexOf('@');
  return at > 0
    ? { name: spec.slice(0, at), version: spec.slice(at + 1) }
    : { name: spec, version: fallbackVersion };
}

const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
const lockfiles = {};
for (const entry of AGENT_CATALOG) {
  const npx = entry.distribution?.npx;
  if (npx === undefined) continue;
  const spec = parseSpec(npx.package, entry.version);
  const dir = mkdtempSync(path.join(os.tmpdir(), `kepcup-lock-${entry.id}-`));
  try {
    const packageJson = {
      name: `kepcup-agent-${entry.id}`,
      private: true,
      dependencies: { [spec.name]: spec.version },
    };
    writeFileSync(path.join(dir, 'package.json'), `${JSON.stringify(packageJson, null, 2)}\n`);
    execFileSync(
      npm,
      [
        'install',
        '--package-lock-only',
        '--ignore-scripts',
        '--omit=dev',
        '--no-audit',
        '--no-fund',
      ],
      { cwd: dir, stdio: ['ignore', 'ignore', 'inherit'], shell: process.platform === 'win32' },
    );
    lockfiles[`${spec.name}@${spec.version}`] = {
      packageJson: JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8')),
      lockfile: JSON.parse(readFileSync(path.join(dir, 'package-lock.json'), 'utf8')),
    };
    process.stderr.write(`locked ${spec.name}@${spec.version}\n`);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const header = `// GENERATED by scripts/generate-agent-lockfiles.mjs — do not edit by hand.
// App-shipped npm lockfiles of the npx-distributed agents (D72): the installer
// runs \`npm ci --ignore-scripts\` against exactly these trees.
import type { NpxLockfile } from './installer.js';

export const AGENT_NPX_LOCKFILES: Readonly<Record<string, NpxLockfile>> = `;
writeFileSync(output, `${header}${JSON.stringify(lockfiles, null, 2)};\n`);
try {
  execFileSync(npm === 'npm' ? 'npx' : 'npx.cmd', ['prettier', '--write', output], {
    cwd: root,
    stdio: 'ignore',
    shell: process.platform === 'win32',
  });
} catch {
  process.stderr.write('prettier not available: output left unformatted\n');
}
process.stderr.write(`wrote ${path.relative(root, output)}\n`);
