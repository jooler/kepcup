import { z } from 'zod';

/**
 * 62.09 项目决议卡（T9）：`cardType: 'resolution'` 的宿主卡片载荷。卡片本体是
 * 项目会话里的一条 `kind='card'` 消息，经 C15 `principalOps.appendCard /
 * updateCard` 写入——载荷在 schema 已知的 `hostCard.data` 槽位（见
 * domain/types.ts cardContentSchema 的 hostCard 注释），这里冻结该 data 的
 * 结构（渲染端按它解析；服务端 team.db `project_resolutions` 是唯一事实来源，
 * 卡片是它的投影视图）。
 *
 * 版本语义（62.09 §2）：签署绑定版本——`update` 把 version +1 并清空全部
 * 已签（快照成员的 approvedVersion 变成「待重签」）；`passed` 后整卡锁定，
 * 修正 / 推翻一律起新决议（`supersedes` 只作关联展示）。
 */

export const RESOLUTION_CARD_TYPE = 'resolution' as const;

/** One human member of the propose-time snapshot and the version they signed. */
export const resolutionSnapshotMemberSchema = z.strictObject({
  /** Team member id (`mbr_…`); opaque to core, the host resolves the card. */
  memberId: z.string().min(1),
  /** Propose-time display name snapshot (deleted members stay identifiable). */
  name: z.string(),
  /**
   * The content version this member signed; null = not signed yet. A non-null
   * value below the card's `version` renders as 「待重签」 (stale signature).
   */
  approvedVersion: z.number().int().min(1).nullable(),
});
export type ResolutionSnapshotMember = z.infer<typeof resolutionSnapshotMemberSchema>;

export const resolutionCardSchema = z.strictObject({
  /** Team-layer resolution id (`res_…`); the RPC surface keys on it. */
  resolutionId: z.string().min(1),
  title: z.string(),
  /** Structured body (目标 / 范围 / 执行要点), generated by the executive lead. */
  body: z.string(),
  /** Content version; signatures bind to it (cleared on update). */
  version: z.number().int().min(1),
  /** Lifecycle state; `passed` locks the card forever. */
  state: z.enum(['open', 'passed', 'withdrawn']),
  /** Propose-time human snapshot with per-member signature versions. */
  snapshot: z.array(resolutionSnapshotMemberSchema),
  /** When the resolution passed (locked); present on `passed` cards. */
  passedAt: z.number().int().optional(),
  /** Who withdrew (member id or bot id), on `withdrawn` cards. */
  withdrawnBy: z.string().min(1).optional(),
  /** When the resolution was withdrawn; present on `withdrawn` cards. */
  withdrawnAt: z.number().int().optional(),
  /** Earlier resolution this one supersedes (display-only relation). */
  supersedes: z.string().min(1).optional(),
});
export type ResolutionCardData = z.infer<typeof resolutionCardSchema>;
